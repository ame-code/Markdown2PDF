'use strict';
/**
 * build-css.cjs — regenerate `mjx-svg-css.js` from the vendored MathJax bundle.
 *
 * The CSS Typora injects for math is `MathJax.svgStylesheet().innerHTML`
 * produced at runtime by the very bundle Typora ships
 * (lib.asar -> lib/MathJax3/es5/tex-svg-full.js, MathJax 3.2.2).  Running that
 * bundle once and capturing the stylesheet keeps our copy byte-identical
 * instead of hand-maintaining 2.7 KB of CSS.
 *
 *   node src/math/build-css.cjs
 */

const fs = require('fs');
const path = require('path');
const core = require('./core.cjs');

(async () => {
  const css = await core.mathjaxSvgStylesheet();
  const out = path.join(__dirname, 'mjx-svg-css.js');
  const header =
    '// GENERATED by src/math/build-css.cjs - do not edit.\n' +
    '// Source: MathJax 3.2.2 `MathJax.svgStylesheet().innerHTML`, extracted from the\n' +
    '// bundle Typora 1.9.5 ships (lib.asar -> lib/MathJax3/es5/tex-svg-full.js).\n' +
    '// Regenerate after changing the bundle/config: node src/math/build-css.cjs\n';
  fs.writeFileSync(out, header + 'export const MATH_CSS = ' + JSON.stringify(css) + ';\nexport default MATH_CSS;\n');
  // CommonJS twin so `require('./src/math')` works in the type:module repo.
  fs.writeFileSync(
    path.join(__dirname, 'mjx-svg-css.cjs'),
    header + 'const MATH_CSS = ' + JSON.stringify(css) + ';\nmodule.exports = { MATH_CSS };\n'
  );
  console.log('math: wrote ' + out + ' (' + css.length + ' chars of CSS)');
  await core.close();
})().catch(async (e) => {
  console.error('build-css: FAILED', e);
  try {
    await core.close();
  } catch (_) {}
  process.exit(1);
});
